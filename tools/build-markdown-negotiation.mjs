#!/usr/bin/env node
// Route requests through a small Pages Function that serves prebuilt Markdown
// for content pages. _routes.json sends everything except the icon and font
// folders, so its rule count no longer grows with the page count (Cloudflare
// allows 100). Cloudflare does not apply _headers to Function responses, so the
// Function sets the static-file headers below itself.
import fs from "node:fs";
import path from "node:path";

const output = path.resolve(process.argv.find((arg) => arg.startsWith("--out="))?.slice(6) || "static");
const sitemap = fs.readFileSync(path.join(output, "sitemap.xml"), "utf8");
const routes = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => new URL(match[1]).pathname);
const map = {};
for (const route of routes) {
  if (route in map) throw new Error(`Duplicate content route: ${route}`);
  const markdown = route.endsWith("/") ? `${route}index.md` : `${route}.md`;
  if (!fs.existsSync(path.join(output, markdown.slice(1))))
    throw new Error(`Markdown companion missing: ${markdown}`);
  map[route] = markdown;
}
if (!map["/"]) throw new Error("Root Markdown route missing");
// Trailing wildcards and exact paths only: those are the patterns Cloudflare documents.
const EXCLUDE = ["/assets/*", "/fonts/*", "/favicon.ico", "/favicon-96.png"];

const worker = `// Generated by tools/build-markdown-negotiation.mjs. Do not edit here.
const markdownRoutes = ${JSON.stringify(map, null, 2)};
// Mirrors the _headers rules for files that pass through this Function.
const staticHeaders = [
  [/\.css$/, { "Cache-Control": "public, max-age=31536000, immutable" }],
  [/\.json$/, { "Cache-Control": "public, max-age=300" }],
  [/\.md$/, { "Content-Type": "text/markdown; charset=utf-8" }],
];

function withHeaders(response, extra) {
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(extra)) headers.set(name, value);
  headers.set("X-Content-Type-Options", "nosniff");
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}

function wantsMarkdown(accept) {
  return accept.split(",").some((part) => {
    const [type, ...parameters] = part.trim().split(";");
    if (type.toLowerCase() !== "text/markdown") return false;
    const quality = parameters.find((parameter) => /^\\s*q\\s*=/i.test(parameter));
    return !quality || Number(quality.split("=")[1].trim()) > 0;
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const markdown = markdownRoutes[url.pathname];
    if (!markdown || !["GET", "HEAD"].includes(request.method)) {
      const response = await env.ASSETS.fetch(request);
      return withHeaders(response, Object.assign({}, ...staticHeaders.filter(([pattern]) => pattern.test(url.pathname)).map(([, h]) => h)));
    }
    const useMarkdown = wantsMarkdown(request.headers.get("Accept") || "");
    if (useMarkdown) url.pathname = markdown;
    const response = await env.ASSETS.fetch(useMarkdown ? new Request(url, request) : request);
    if (!response.ok) return response;
    const headers = new Headers(response.headers);
    const vary = headers.get("Vary");
    if (!vary?.split(",").some((value) => value.trim().toLowerCase() === "accept"))
      headers.set("Vary", vary ? vary + ", Accept" : "Accept");
    if (useMarkdown) headers.set("Content-Type", "text/markdown; charset=utf-8");
    // The zone CDN does not currently key its HTML cache by Accept. Keep
    // browser caching, but never share one representation across CDN clients.
    headers.set("Cache-Control", "private, max-age=300");
    headers.set("Cloudflare-CDN-Cache-Control", "no-store");
    headers.set("X-Content-Type-Options", "nosniff");
    return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
  },
};
`;
fs.writeFileSync(path.join(output, "_worker.js"), worker);
fs.writeFileSync(path.join(output, "_routes.json"), JSON.stringify({ version: 1, include: ["/*"], exclude: EXCLUDE }, null, 2) + "\n");
console.log(`Generated Markdown negotiation for ${routes.length} content routes`);
